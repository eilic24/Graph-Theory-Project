#COVID Pandemic
import networkx as nx
import random
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.animation import FuncAnimation

# Create graph with nodes
G = nx.erdos_renyi_graph(100, 0.2)

#Initial set up
red_node = 0
pos = nx.spring_layout(G)
pos[red_node] = (0, 0)

# Colors
node_colors = ['gray' for _ in G.nodes]
affected_nodes = []  # Infected (red)
recovered_nodes = []  # Recovered (blue)
dead_nodes = []  # Died (purple)
infection_probability = 0.25

#Infection spreading simulation
fig, ax = plt.subplots(figsize=(10, 8))
nodes = nx.draw_networkx_nodes(G, pos, node_size=500, node_color=node_colors, ax=ax)
edges = nx.draw_networkx_edges(G, pos, ax=ax)
labels = nx.draw_networkx_labels(G, pos, ax=ax)
title = ax.set_title("Day 0: No Infection")

# Interaction model
def animate(frame):
    global affected_nodes, node_colors, recovered_nodes, dead_nodes
    if frame == 0: # Initial infection, starting with node 0
        affected_nodes = [red_node]
        node_colors[red_node] = 'red'
    else:
        newly_infected = []
        for node in affected_nodes:
            if node not in recovered_nodes and node not in dead_nodes:
# 80% chance of recovery
                if random.random() < 0.80:
                    node_colors[node] = 'lightblue'
                    recovered_nodes.append(node)
                    continue
# 20% chance of death
                if random.random() < 0.20:
                    node_colors[node] = 'purple'
                    dead_nodes.append(node)
                    continue
        for node in affected_nodes:
            for neighbor in G.neighbors(node):
                if neighbor not in affected_nodes and random.random() < infection_probability:
                    newly_infected.append(neighbor)
                    node_colors[neighbor] = 'red'
        affected_nodes.extend(newly_infected)

    # Update node colors
    nodes.set_color(node_colors)
    title.set_text(f"Day {frame}: Spread of Disease (Recovery & Death included)")
    return nodes, title
ani = FuncAnimation(fig, animate, frames=101, interval=100, blit=False, repeat=False)

# Show
from IPython.display import HTML
HTML(ani.to_jshtml())